#!/usr/bin/env node
// scripts/docs.cjs — the live documentation generator.
//
// Interprets docs/program.js: every programming BEAT drives the real thing in
// Chromium (the committed registry served to a plain third-party page, or the
// unpacked extension injected into a bare page), captures a frame, and the
// generator renders docs/index.html with those frames, live captions and the
// clipboard payload that was actually copied.
//
// Small on purpose: the shared `menu/scripts/e2e-comic` pipeline (C1 → C3) is
// the heavy sibling; this is the two-page version with the same vocabulary
// (run · beat · caption · frame). Regenerated by `npm run docs` and by the
// release script, so the docs ship with the version they describe.
//
// Usage: node scripts/docs.cjs   (requires the dev dependency: playwright, chromium)
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const { chromium } = require('playwright');

const { startServer } = require('../test/e2e/lib/serve');
const { dragFabTo, readClipboard } = require('../test/e2e/lib/gestures');
const { copyExtension, launchWithExtension, triggerInjection } = require('../test/e2e/lib/extension-harness');
const program = require('../docs/program');

const ROOT = path.join(__dirname, '..');
const DOCS = path.join(ROOT, 'docs');
const ASSETS = path.join(DOCS, 'assets');
const VIEWPORT = { width: 1280, height: 800 };
const MOBILE = { width: 390, height: 700 };
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));

function ok(msg) { process.stdout.write(`✓  ${msg}\n`); }
function log(msg) { process.stdout.write(`▶  ${msg}\n`); }
function die(msg) { process.stderr.write(`✗  ${msg}\n`); process.exit(1); }
function shortSha() {
    try { return execFileSync('git', ['-C', ROOT, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim(); }
    catch (e) { return 'unknown'; }
}

async function waitFor(predicate, { timeout = 15000, interval = 100, what = 'condition' } = {}) {
    const started = Date.now();
    for (;;) {
        const value = await predicate();
        if (value) return value;
        if (Date.now() - started > timeout) throw new Error(`timed out waiting for ${what}`);
        await new Promise((r) => setTimeout(r, interval));
    }
}

// ── scenes ────────────────────────────────────────────────────────────
//
// A scene owns one browser + one server and knows how to produce its named
// shots. `shot()` returns { frame, payload? } — the frame is the visible state
// the beat's caption claims.

function embedScene(srv) {
    let browser;
    let context;
    let page;
    let mobileContext;

    async function freshPage(route) {
        context = await browser.newContext({ viewport: VIEWPORT });
        await context.grantPermissions(['clipboard-read', 'clipboard-write'], { origin: srv.base });
        page = await context.newPage();
        await page.goto(srv.base + (route || '/embed'));
        await page.waitForSelector('#fab', { state: 'visible' });
        return page;
    }

    return {
        async open() {
            browser = await chromium.launch({ headless: true });
            await freshPage();
            ok('embed scene: plain third-party page with the published registry files');
        },
        async shot(name, file) {
            if (name === 'mobile') {
                mobileContext = await browser.newContext({ viewport: MOBILE });
                const p = await mobileContext.newPage();
                await p.goto(srv.base + '/embed');
                await p.waitForSelector('#fab', { state: 'visible' });
                await p.screenshot({ path: file, type: 'jpeg', quality: 82 });
                await mobileContext.close();
                mobileContext = null;
                return {};
            }
            if (!page) await freshPage();
            if (name === 'idle') {
                await page.screenshot({ path: file, type: 'jpeg', quality: 82 });
                return {};
            }
            if (name === 'drag') {
                const box = await page.locator('#first-copy').boundingBox();
                if (!box) throw new Error('embed scene: #first-copy is not visible');
                // capture MID-drag: press, drag over the block, shoot, then release
                // (the release completes the pick so the 'copied' beat is settled).
                const fab = await page.locator('#fab').boundingBox();
                const sx = fab.x + fab.width / 2;
                const sy = fab.y + fab.height / 2;
                await page.mouse.move(sx, sy);
                await page.mouse.down();
                await page.mouse.move(sx - 120, sy, { steps: 5 });
                await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2, { steps: 10 });
                await page.waitForSelector('.inspector-overlay', { state: 'visible' });
                await page.screenshot({ path: file, type: 'jpeg', quality: 82 });
                await page.mouse.up();
                return {};
            }
            if (name === 'copied') {
                const payload = await waitFor(
                    async () => { const t = await readClipboard(page).catch(() => ''); return t && t.includes('URL:') ? t : ''; },
                    { what: 'the clipboard payload after the pick' }
                );
                await page.waitForSelector('.inspector-overlay', { state: 'visible' });
                await page.screenshot({ path: file, type: 'jpeg', quality: 82 });
                return { payload };
            }
            if (name === 'metadata') {
                // A page that annotates its blocks: pick the paragraph inside the
                // [data-evidence-node] card so the payload gains Context/Captured/Evidence.
                await context.close();
                await freshPage('/embed-metadata');
                const box = await page.locator('#meta-copy').boundingBox();
                if (!box) throw new Error('embed scene: #meta-copy is not visible');
                await dragFabTo(page, box.x + box.width / 2, box.y + box.height / 2);
                await page.waitForSelector('.inspector-overlay', { state: 'visible' });
                const payload = await waitFor(
                    async () => { const t = await readClipboard(page).catch(() => ''); return t && t.includes('Context:') ? t : ''; },
                    { what: 'the enriched clipboard payload (Context/Captured/Evidence)' }
                );
                await page.screenshot({ path: file, type: 'jpeg', quality: 82 });
                return { payload };
            }
            if (name === 'devsheet') {
                // INSP-007 — the same sheet after the embedder opted in.
                await context.close();
                await freshPage('/embed?dev=1');
                await page.locator('#fab').click();
                await page.waitForFunction(() => {
                    const t = document.getElementById('fabSheetTitle');
                    const s = document.getElementById('fabSheet');
                    return !!t && t.textContent === 'Developer tools' && !!s && s.classList.contains('open');
                });
                await page.waitForTimeout(350);
                await page.screenshot({ path: file, type: 'jpeg', quality: 82 });
                return {};
            }
            if (name === 'sheet') {
                // reset to a clean page so the sheet opens from the idle FAB
                await context.close();
                await freshPage();
                await page.locator('#fab').click();
                await page.waitForFunction(() => {
                    const s = document.getElementById('fabSheet');
                    return !!s && s.classList.contains('open');
                });
                await page.waitForTimeout(350); // the sheet's transition must finish before the frame
                await page.screenshot({ path: file, type: 'jpeg', quality: 82 });
                return {};
            }
            throw new Error(`embed scene: unknown shot ${JSON.stringify(name)}`);
        },
        async close() {
            if (mobileContext) await mobileContext.close();
            if (context) await context.close();
            if (browser) await browser.close();
        },
    };
}

function extensionScene(srv) {
    let context;
    let worker;
    let page;

    async function freshPage() {
        page = await context.newPage();
        await context.grantPermissions(['clipboard-read', 'clipboard-write'], { origin: srv.base });
        await page.goto(srv.base + '/');
        return page;
    }

    return {
        async open() {
            const extensionDir = copyExtension(path.join(ROOT, 'extension'));
            const launched = await launchWithExtension(extensionDir);
            context = launched.context;
            worker = launched.worker;
            await freshPage();
            ok('extension scene: bare third-party page, unpacked extension loaded in Chromium');
        },
        async shot(name, file) {
            if (name === 'bare') {
                if ((await page.locator('#fab').count()) !== 0) throw new Error('extension scene: page is not clean before injection');
                await page.screenshot({ path: file, type: 'jpeg', quality: 82 });
                return {};
            }
            if (name === 'injected') {
                await triggerInjection(worker, page);
                await page.waitForSelector('#fab', { state: 'visible' });
                await page.screenshot({ path: file, type: 'jpeg', quality: 82 });
                return {};
            }
            if (name === 'pick') {
                const box = await page.locator('#first-copy').boundingBox();
                if (!box) throw new Error('extension scene: #first-copy is not visible');
                await dragFabTo(page, box.x + box.width / 2, box.y + box.height / 2);
                await page.waitForSelector('.inspector-overlay', { state: 'visible' });
                await page.screenshot({ path: file, type: 'jpeg', quality: 82 });
                return {};
            }
            if (name === 'copied') {
                const payload = await waitFor(
                    async () => { const t = await readClipboard(page).catch(() => ''); return t && t.includes('URL:') ? t : ''; },
                    { what: 'the clipboard payload after the extension pick' }
                );
                await page.screenshot({ path: file, type: 'jpeg', quality: 82 });
                return { payload };
            }
            throw new Error(`extension scene: unknown shot ${JSON.stringify(name)}`);
        },
        async close() { if (context) await context.close(); },
    };
}

// ── rendering ─────────────────────────────────────────────────────────

function esc(s) {
    return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

/** Minimal inline markdown: **bold**, `code`. */
function inline(s) {
    return esc(s)
        .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
        .replace(/`([^`]+)`/g, '<code>$1</code>');
}

function paragraphs(lines) {
    const out = [];
    let buf = [];
    const flush = () => { if (buf.length) { out.push(`<p>${buf.map(inline).join(' ')}</p>`); buf = []; } };
    for (const line of lines) {
        if (line.trim() === '') flush();
        else buf.push(line);
    }
    flush();
    return out.join('\n');
}

function codeBlock(lines) {
    return `<pre class="cmd"><code>${esc(lines.join('\n'))}</code></pre>`;
}

/** Colourize one clipboard payload for display (escaped; raw text unchanged). */
function highlightPayload(text) {
    return String(text).split('\n').map((line) => {
        const key = /^(URL|Path|Context|Captured|Evidence|HTML):\s?(.*)$/.exec(line);
        if (key) {
            const rest = key[2] === '' ? '' : ' ' + esc(key[2]);
            return `<span class="pk pk-${key[1].toLowerCase()}">${key[1]}:</span>${rest}`;
        }
        const fact = /^(\s{2})([A-Za-z0-9_.-]+):\s?(.*)$/.exec(line);
        if (fact) return `${fact[1]}<span class="pfk">${esc(fact[2])}:</span> <span class="pfv">${esc(fact[3])}</span>`;
        return `<span class="ph">${esc(line)}</span>`;
    }).join('\n');
}

function frameFigure(n, beat, imgRel, payload) {
    return `<figure class="beat">
      <img src="${esc(imgRel)}" alt="${esc(beat.caption)}" loading="lazy" class="zoomable" tabindex="0" role="button" aria-label="Enlarge frame ${n}: ${esc(beat.caption)}">
      <span class="zoom-hint" aria-hidden="true">⤢</span>
      <figcaption><span class="num">${n}</span>${inline(beat.caption)}</figcaption>
      ${payload ? `<pre class="clip"><code>${highlightPayload(payload)}</code></pre>` : ''}
    </figure>`;
}

