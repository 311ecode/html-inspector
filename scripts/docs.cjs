// ── main ──────────────────────────────────────────────────────────────

(async () => {
    fs.rmSync(ASSETS, { recursive: true, force: true });
    fs.mkdirSync(ASSETS, { recursive: true });

    const srv = await startServer({ registryBase: '/registry' });
    const scenes = { embed: embedScene(srv), extension: extensionScene(srv) };
    const opened = new Set();
    const frameOf = new Map();
    const latest = { value: null };

    try {
        latest.value = JSON.parse(fs.readFileSync(path.join(ROOT, 'registry', 'index.json'), 'utf8')).latest;

        const planned = [];
        for (const section of program.sections) for (const beat of section.beats) planned.push(beat);
        for (let i = 0; i < planned.length; i++) {
            const beat = planned[i];
            const scene = scenes[beat.scene];
            if (!scene) throw new Error(`docs program: unknown scene ${JSON.stringify(beat.scene)}`);
            if (!opened.has(beat.scene)) { await scene.open(); opened.add(beat.scene); }
            const n = i + 1;
            const rel = path.join('assets', `${String(n).padStart(2, '0')}-${beat.scene}-${beat.shot}.jpg`);
            const file = path.join(DOCS, rel);
            const { payload } = await scene.shot(beat.shot, file);
            frameOf.set(beat, { n, rel, payload: payload || null });
            log(`frame ${n}: ${beat.scene}/${beat.shot} -> docs/${rel}`);
        }
    } finally {
        for (const name of opened) await scenes[name].close();
        await srv.close();
    }

    const html = render(program.sections, { latest: latest.value, frameOf });
    fs.writeFileSync(path.join(DOCS, 'index.html'), html);
    ok(`${frameOf.size} live frames + docs/index.html (v${pkg.version}, registry ${latest.value})`);
})().catch((err) => {
    process.stderr.write(`✗  ${err && err.stack ? err.stack : err}\n`);
    process.exit(1);
});
